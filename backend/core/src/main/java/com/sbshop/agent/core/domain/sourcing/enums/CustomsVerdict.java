package com.sbshop.agent.core.domain.sourcing.enums;

/**
 * 통관(구매대행 가능 여부) 게이트 판정.
 *
 * <p>식약처 「해외직구식품 국내 반입차단 대상 원료·성분」 목록과 상품 성분표를 대조한 결과다.
 * 이 게이트는 <b>1차 스크리닝</b>이며 최종 통관 책임을 대신하지 않는다 —
 * 그래서 애매한 경우를 조용히 통과시키지 않고 {@link #REVIEW}로 올려 사람이 보게 한다.
 */
public enum CustomsVerdict {

	/** 반입차단 성분이 검출되지 않았다. */
	PASS,

	/**
	 * 사람이 확인해야 한다. 다음 중 하나다:
	 * <ul>
	 *   <li>성분표를 추출하지 못함 (추출 실패를 PASS로 처리하면 차단성분을 놓친다)</li>
	 *   <li>차단성분과 유사하지만 확정할 수 없는 표기</li>
	 *   <li>축산물·의약품성 성분 등 추가 규제 가능성</li>
	 * </ul>
	 * 추천 목록에 경고와 함께 노출되고, 사용자가 명시적으로 승인해야 등록할 수 있다.
	 */
	REVIEW,

	/** 반입차단 성분이 확인됐다. 추천 목록에서 제외한다. */
	BLOCKED,

	/** 아직 판정하지 않았다(상세 크롤 전). */
	UNKNOWN
}
