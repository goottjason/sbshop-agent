// 전화번호를 하이픈 없는 숫자만으로 정규화한다(예: 01000000000).
// 마켓마다 하이픈 유무가 제각각(쿠팡·스마트스토어는 하이픈 없이 저장되기도 한다)이라
// 표시 시점에 숫자만 남겨 형식을 통일한다.
//
// 하이픈을 붙이지 않는 이유: 이 값은 읽는 것보다 **택배·마켓 시스템에 그대로 옮겨 붙이는**
// 용도가 많다. 하이픈이 있으면 붙여넣은 뒤 매번 지워야 한다.
//
// 숫자가 하나도 없으면 원본을 그대로 둔다(빈 값·이상 데이터를 조용히 삼키지 않기 위해).
export function formatPhone(raw?: string | null): string {
  if (!raw) return '';
  const digits = raw.replace(/\D/g, '');
  return digits || raw;
}
